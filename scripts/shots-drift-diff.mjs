#!/usr/bin/env node
/**
 * scripts/shots-drift-diff.mjs — post-mortem tool for the website/shot-*.webp
 * drift gate (BET-537).
 *
 * When the drift gate fails, CI uploads a pair of byte sets — the freshly
 * regenerated shots (`regenerated/`) and the committed ones (`committed/`) —
 * so a human/offline process can see WHAT differs, not just that something
 * does. This script turns that pair into evidence:
 *
 *   - A report.txt mapping every drifting shot to its byte sizes (committed vs
 *     regenerated) and a one-line classification hint.
 *   - A <name>.diff.png per drifting shot: an absolute per-pixel difference
 *     between the two frames (scaled so any change is visible) so the class of
 *     difference — a systematic geometric offset vs isolated text runs vs a
 *     font/glyph substitution — can be named at a glance.
 *
 * It is deliberately byte-comparison-first: artifact diffing must never depend
 * on an eyeball. The `diff.png` is an aid; the authoritative signal is that the
 * committed and regenerated bytes are not equal.
 *
 * Usage:
 *   node scripts/shots-drift-diff.mjs <pair-dir>
 *
 * `<pair-dir>` is expected to contain `committed/` and `regenerated/`
 * subdirectories (the layout CI's drift-failure artifact step produces). The
 * script writes report.txt + *.diff.png into `<pair-dir>/diff/`.
 */

import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import sharp from "sharp";

const [pairDir] = process.argv.slice(2);
if (!pairDir) {
  console.error("usage: node scripts/shots-drift-diff.mjs <pair-dir>");
  process.exit(2);
}

const committedDir = join(pairDir, "committed");
const regeneratedDir = join(pairDir, "regenerated");
const outDir = join(pairDir, "diff");

function listFiles(dir) {
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith(".webp"))
      .sort();
  } catch {
    return [];
  }
}

async function pixelDiff(committedPath, regeneratedPath, outPath) {
  const [a, b] = await Promise.all([
    sharp(committedPath).raw().toBuffer({ resolveWithObject: true }),
    sharp(regeneratedPath).raw().toBuffer({ resolveWithObject: true }),
  ]);
  const { info: aInfo, data: aData } = a;
  const { info: bInfo, data: bData } = b;
  const w = Math.min(aInfo.width, bInfo.width);
  const h = Math.min(aInfo.height, bInfo.height);
  const channels = Math.min(aInfo.channels, bInfo.channels, 3);
  const diff = Buffer.alloc(w * h);
  let changed = 0;
  for (let p = 0; p < w * h; p++) {
    let maxDelta = 0;
    for (let c = 0; c < channels; c++) {
      const di = Math.abs(aData[p * aInfo.channels + c] - bData[p * bInfo.channels + c]);
      if (di > maxDelta) maxDelta = di;
    }
    // Abs difference scaled 4x so subtle antialiasing changes are visible.
    diff[p] = Math.min(255, maxDelta * 4);
    if (maxDelta > 0) changed++;
  }
  await sharp(diff, { raw: { width: w, height: h, channels: 1 } })
    .png()
    .toFile(outPath);
  return { changed, total: w * h, w, h };
}

async function main() {
  const committed = listFiles(committedDir);
  const regenerated = listFiles(regeneratedDir);
  const names = [...new Set([...committed, ...regenerated])].sort();
  mkdirSync(outDir, { recursive: true });

  const lines = [];
  lines.push(`Pixel diff of committed vs regenerated shot sets (BET-537 drift gate)`);
  lines.push(`committed dir: ${committedDir} (${committed.length} files)`);
  lines.push(`regenerated dir: ${regeneratedDir} (${regenerated.length} files)`);
  lines.push("");

  for (const name of names) {
    const cPath = join(committedDir, name);
    const rPath = join(regeneratedDir, name);
    const hasC = committed.includes(name);
    const hasR = regenerated.includes(name);
    if (!hasC || !hasR) {
      lines.push(`${name}: MISSING ${hasC ? "regenerated" : "committed"} side (byte difference cannot be classified)`);
      continue;
    }
    const cSize = statSync(cPath).size;
    const rSize = statSync(rPath).size;
    if (cSize === rSize) {
      // Same byte length is not equality, but it's a strong signal — do a real
      // compare only when sizes match to avoid decoding identical-size images.
      const [ca, ra] = await Promise.all([
        sharp(cPath).raw().toBuffer(),
        sharp(rPath).raw().toBuffer(),
      ]);
      if (ca.equals(ra)) {
        lines.push(`${name}: IDENTICAL (${cSize} bytes)`);
        continue;
      }
      lines.push(`${name}: DIFFERS (${cSize} vs ${rSize} bytes)`);
    } else {
      lines.push(`${name}: DIFFERS (${cSize} vs ${rSize} bytes)`);
    }
    const diffOut = join(outDir, `${name}.diff.png`);
    try {
      const { changed, total, w, h } = await pixelDiff(cPath, rPath, diffOut);
      const pct = ((changed / total) * 100).toFixed(2);
      lines.push(`    diff.png ${w}x${h}, ${changed}/${total} px changed (${pct}%)`);
    } catch (e) {
      lines.push(`    diff.png FAILED: ${e.message}`);
    }
  }

  writeFileSync(join(outDir, "report.txt"), lines.join("\n") + "\n");
  console.log(lines.join("\n"));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
